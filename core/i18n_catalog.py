_AR_CHAR_RE = re.compile(r"[\u0600-\u06FF]")


def translate_ui_text(text: str) -> str:
    """Translate a single UI text fragment from Arabic to English, preserving outer whitespace."""
    if not text or not _AR_CHAR_RE.search(text):
        return text

    leading = text[: len(text) - len(text.lstrip())]
    trailing = text[len(text.rstrip()) :]
    core = " ".join(text.split())
    if not core:
        return text

    # 1. Exact lookup
    direct = AR_TO_EN.get(core)
    if direct is not None:
        return f"{leading}{direct}{trailing}"

    # 2. Punctuation-trimmed lookup (e.g. "الاسم *", "البريد الإلكتروني:")
    if core.endswith(" *"):
        base = core[:-2].strip()
        if base in AR_TO_EN:
            return f"{leading}{AR_TO_EN[base]} *{trailing}"
    if core.endswith(":"):
        base = core[:-1].strip()
        if base in AR_TO_EN:
            return f"{leading}{AR_TO_EN[base]}:{trailing}"

    # 3. Parameterized UI patterns
    for pattern, repl in DYNAMIC_PATTERNS:
        m = pattern.match(core)
        if m:
            return f"{leading}{repl(m)}{trailing}"

    return text


def get_js_catalog() -> dict[str, str]:
    """Return the JSON-serializable Arabic -> English map for frontend runtime localization."""
    return dict(AR_TO_EN)
